void reset_system( void ) {
    *AUDIO_DMA_L_STATUS = 1; *AUDIO_DMA_R_STATUS = 1;
    for( int i = 0; i < 6; i++ ) AUDIO_DURATION[ i ] = 0;

    *GPU_DITHERMODE = 0;
    *CROP_LEFT = 0; *CROP_RIGHT = 319; *CROP_TOP = 0; *CROP_BOTTOM = 239;
    *FRAMEBUFFER_DRAW = 3; gpu_cs(); while( !*GPU_FINISHED );
    *FRAMEBUFFER_DRAW = 1; *BITMAP_DISPLAY256 = 0;
    *SCREENORDER = ( 3 << 0 ) | ( 1 << 4 ) | ( 4 << 8 ) | ( 8 << 12 ) | ( 9 << 16 ) | ( 10 << 20 ) | ( 11 << 24 );
    *COLOUR = 0;
    tpu_cs(); *TPU_LOREZ = 0;
    *TM_LOREZ = 0;
    for( int i = 0; i < 4; i++ ) {
        tm_cs( i );
        TM_SCROLLAMOUNT[i] = 1;
    }
    for( int i = 0; i < 63; i++ ) SPRITE_ACTIVE[i] = 0;
}

void timer_interrupt( void ) {
    tpu_set( 0, 17, TRANSPARENT, WHITE, 1 );
    long rtc = *RTC + 0x2000000000000000;
    for( int i = 0; i < 16; i++ ) {
        rtc = _rv64_rol( rtc, 4 );
        switch(i) {
            case 8: case 9: break;
            default: tpu_output_character( 48 + ( rtc & 0xf ) );
        }
        switch(i) {
            case 3: case 5: tpu_output_character('-'); break;
            case 7: tpu_output_character(' '); break;
            case 11: case 13: tpu_output_character(':'); break;
        }
    }
}

void vblank_interrupt( void ) {
    static int j = 0;

    tilemap_scroll( 0, 3, 1 );
    tilemap_scroll( 1, 1, 1 );
    tilemap_scroll( 2, 1, 1 );
    tilemap_scroll( 3, 3, 1 );
    update_sprite( 0, 0, 1, 0, 0 ); update_sprite( 2, 0, 1, 0, 0 );
    set_sprite_attribute( 0, 1, ( ( j & 192 ) >> 6 ) );
    set_sprite_attribute( 2, 1, ( j & 128 ) >> 7 );
    j++;
}

void mandel( void ) {
    const int graphwidth = 320, graphheight = 100;
    float kt = 63, m = 4.0;
    float xmin = -2.1, xmax = 0.6, ymin = -1.35, ymax = 1.35;
    float dx = (xmax - xmin) / graphwidth, dy = (ymax - ymin) / graphheight;
    float jx, jy, tx, ty, wx, wy, r;
    int k;

    gpu_pixelblock_start( 0, 122, 320 );
    for( int y = 0; y < graphheight; y++ ) {
        jy = ymin + y * dy;
        for( int x = 0; x < graphwidth; x++ ) {
            jx = xmin + x * dx;
            k = 0; wx = 0.0; wy = 0.0;
            do {
                tx = wx * wx - wy * wy + jx;
                ty = 2.0 * wx * wy + jy;
                wx = tx;
                wy = ty;
                r = wx * wx + wy * wy;
                k = k + 1;
            } while( ( r < m ) && ( k < kt ) );

            *PB_COLOUR = ( k > kt ) ? BLACK : k + 1;
        }
    }
    *PB_STOP = 3;
}

void __attribute__((interrupt ("machine"))) interrupt_handler() {
    long what_irq = IRQ_CAUSE();

    if( what_irq == IRQ_CAUSE_TIMER ) {
        IRQ_ACK( IRQ_TIMER );
        timer_interrupt();
        IRQ_SET_TIMER_QUICK( 1 );
    } else {
        if( what_irq == IRQ_CAUSE_VBLANK ) {
            IRQ_ACK( IRQ_VBLANK );
            vblank_interrupt();
        } else {
            IRQ_ACK( 1 << what_irq );
        }
    }
}

